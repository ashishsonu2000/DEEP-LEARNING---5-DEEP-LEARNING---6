using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using EazyEdu.Web.Models;

namespace EazyEdu.Web.Services
{
    /// <summary>Builds the plain-text and printable HTML documents the chat offers for download.</summary>
    public class DocumentService
    {
        private const string Rule = "--------------------------------------------------";

        public string BuildPracticePaper(PracticePaper paper, bool includeAnswers)
        {
            if (paper == null) return string.Empty;

            var sb = new StringBuilder();
            sb.AppendLine("EAZYEDU — GENERATED PRACTICE PAPER");
            sb.AppendLine(Rule);
            sb.AppendLine("Student   : " + paper.StudentName);
            sb.AppendLine("Class     : " + paper.ClassName);
            sb.AppendLine("Subject   : " + paper.Subject);
            sb.AppendLine("Difficulty: " + paper.Difficulty);
            sb.AppendLine(string.Format(CultureInfo.InvariantCulture, "Duration  : {0} min    Max marks: {1}", paper.DurationMinutes, paper.TotalMarks));
            sb.AppendLine("Generated : " + Clock.Now.ToString("dd MMM yyyy, HH:mm", CultureInfo.InvariantCulture));
            sb.AppendLine(Rule);
            sb.AppendLine();
            sb.AppendLine("QUESTIONS");
            sb.AppendLine();

            for (int i = 0; i < paper.Questions.Count; i++)
            {
                PracticeQuestion q = paper.Questions[i];
                sb.AppendLine(string.Format(CultureInfo.InvariantCulture, "{0}. {1}   [{2} mark(s), {3}]", i + 1, q.Question, q.Marks, q.Difficulty));
                sb.AppendLine();
            }

            if (includeAnswers)
            {
                sb.AppendLine(Rule);
                sb.AppendLine("ANSWER KEY");
                sb.AppendLine();
                for (int i = 0; i < paper.Questions.Count; i++)
                    sb.AppendLine(string.Format(CultureInfo.InvariantCulture, "{0}. {1}", i + 1, paper.Questions[i].Answer));
            }

            sb.AppendLine(Rule);
            sb.AppendLine("Generated by the EazyEdu assistant from the " + paper.ClassName + " syllabus. For self-practice only.");
            return sb.ToString();
        }

        public string BuildFeeReceipt(Student student)
        {
            if (student == null) return string.Empty;

            FeeAccount fee = student.Fee;
            var sb = new StringBuilder();
            sb.AppendLine("EAZYEDU SCHOOL — FEE STATEMENT");
            sb.AppendLine(Rule);
            sb.AppendLine("Student       : " + student.Name);
            sb.AppendLine("Class         : " + student.ClassName);
            sb.AppendLine("Academic year : " + fee.AcademicYear);
            sb.AppendLine("Installment   : " + fee.Installment);
            sb.AppendLine("Statement date: " + Clock.Today.ToString("dd MMM yyyy", CultureInfo.InvariantCulture));
            sb.AppendLine(Rule);
            sb.AppendLine("Total fee     : " + Money(fee.Total));
            sb.AppendLine("Paid to date  : " + Money(fee.Paid));
            sb.AppendLine("Balance due   : " + Money(fee.Balance));
            sb.AppendLine("Due date      : " + (fee.DueDate.HasValue ? fee.DueDate.Value.ToString("dd MMM yyyy", CultureInfo.InvariantCulture) : "—"));
            sb.AppendLine(Rule);
            sb.AppendLine("HEAD-WISE BREAKDOWN");
            foreach (FeeComponent component in fee.Components)
                sb.AppendLine(string.Format(CultureInfo.InvariantCulture, "  {0,-24}{1}", component.Head, Money(component.Amount)));

            if (student.Payments.Count > 0)
            {
                sb.AppendLine(Rule);
                sb.AppendLine("PAYMENTS RECEIVED");
                foreach (FeePayment payment in student.Payments.OrderBy(p => p.Date))
                {
                    sb.AppendLine(string.Format(CultureInfo.InvariantCulture, "  {0}  {1,-12}  {2,-14}  {3}",
                        payment.Date.ToString("dd MMM yyyy", CultureInfo.InvariantCulture),
                        Money(payment.Amount),
                        payment.Mode,
                        payment.ReceiptNo));
                }
            }

            sb.AppendLine(Rule);
            sb.AppendLine("This is a system-generated statement, not a tax receipt.");
            return sb.ToString();
        }

        public string BuildTranscript(IEnumerable<ChatTurn> turns, Student student)
        {
            var sb = new StringBuilder();
            sb.AppendLine("EAZYEDU — CHAT TRANSCRIPT");
            sb.AppendLine(Rule);
            if (student != null)
            {
                sb.AppendLine("Student : " + student.Name + " (" + student.ClassName + ")");
            }
            sb.AppendLine("Exported: " + Clock.Now.ToString("dd MMM yyyy, HH:mm", CultureInfo.InvariantCulture));
            sb.AppendLine(Rule);
            sb.AppendLine();

            foreach (ChatTurn turn in turns)
            {
                string who = string.Equals(turn.Author, "bot", StringComparison.OrdinalIgnoreCase) ? "EazyEdu" : "You";
                sb.AppendLine(string.Format(CultureInfo.InvariantCulture, "[{0:HH:mm}] {1}: {2}",
                    turn.TimestampUtc.ToLocalTime(), who, turn.Text));

                if (!string.IsNullOrEmpty(turn.Intent) && string.Equals(turn.Author, "user", StringComparison.OrdinalIgnoreCase))
                    sb.AppendLine(string.Format(CultureInfo.InvariantCulture, "        (intent: {0}, confidence: {1:P0})", turn.Intent, turn.Confidence));

                sb.AppendLine();
            }

            sb.AppendLine(Rule);
            sb.AppendLine("Answers came from live school records. Verify critical dates with the school office.");
            return sb.ToString();
        }

        private static string Money(decimal amount)
        {
            return "INR " + amount.ToString("N0", CultureInfo.GetCultureInfo("en-IN"));
        }
    }
}
